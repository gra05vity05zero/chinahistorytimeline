// 人物名から、伝記（bio）が用意されている場合のみ個別ページへのリンクを探す（時代は横断して検索）
function findPersonHref(name) {
  for (const era of ERAS) {
    const figure = getEraFigures(era).find((f) => stripRuby(f.name).startsWith(name));
    if (figure && figure.bio) return `/people/${era.id}/${encodeURIComponent(personSlug(figure.name))}`;
  }
  return null;
}

function eraHref(id) {
  return ERAS.some((e) => e.id === id) ? `/eras/${id}` : null;
}

